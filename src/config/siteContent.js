export function getSiteContent() {
  try {
    const saved = JSON.parse(localStorage.getItem(SITE_CONTENT_KEY) || '{}');
    const placeholderOlds = [
      '243810000000',
      'https://linkedin.com',
      'https://x.com',
      'https://facebook.com',
      'https://instagram.com',
      'https://youtube.com'
    ];
    if (placeholderOlds.includes(saved.whatsapp)) saved.whatsapp = DEFAULT_SITE_CONTENT.whatsapp;
    if (placeholderOlds.includes(saved.linkedin)) saved.linkedin = DEFAULT_SITE_CONTENT.linkedin;
    if (placeholderOlds.includes(saved.twitter)) saved.twitter = DEFAULT_SITE_CONTENT.twitter;
    if (placeholderOlds.includes(saved.facebook)) saved.facebook = DEFAULT_SITE_CONTENT.facebook;
    if (placeholderOlds.includes(saved.instagram)) saved.instagram = DEFAULT_SITE_CONTENT.instagram;
    if (placeholderOlds.includes(saved.youtube)) saved.youtube = DEFAULT_SITE_CONTENT.youtube;
    if (!saved.tiktok) saved.tiktok = DEFAULT_SITE_CONTENT.tiktok;
    if (!saved.whatsappDisplay) saved.whatsappDisplay = DEFAULT_SITE_CONTENT.whatsappDisplay;
    if (!saved.contactEmail || saved.contactEmail.includes('contact@mbegucapital') || saved.contactEmail.includes('contact@')) {
      saved.contactEmail = 'mbegucapital@gmail.com';
    }

    const merged = { ...DEFAULT_SITE_CONTENT, ...saved };
    delete merged.navLogin;
    try {
      localStorage.setItem(SITE_CONTENT_KEY, JSON.stringify(merged));
    } catch {
      // storage ignored
    }
    return merged;
  } catch {
    return DEFAULT_SITE_CONTENT;
  }
}
